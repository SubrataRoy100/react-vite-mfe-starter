import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const MANIFEST_PATH = resolve(process.cwd(), "remotes.manifest.json");
const TARGET_DTS_PATH = resolve(process.cwd(), "packages/host/src/remotes.d.ts");

export function generateRemotesDts() {
  if (!existsSync(MANIFEST_PATH)) {
    console.warn(`[generate-remotes-dts] Manifest not found at: ${MANIFEST_PATH}. Skipping generation.`);
    return;
  }

  let manifest;
  try {
    manifest = JSON.parse(readFileSync(MANIFEST_PATH, "utf-8"));
  } catch (err) {
    console.warn(`[generate-remotes-dts] Failed to parse manifest: ${err.message}. Skipping generation.`);
    return;
  }

  const declarations = [
    "/**",
    " * Ambient Module Declarations for Federated Micro-Frontend Remotes.",
    " * Auto-generated by scripts/generate-remotes-dts.js from remotes.manifest.json.",
    " * DO NOT EDIT DIRECTLY.",
    " */",
    "",
  ];

  for (const [remoteName, config] of Object.entries(manifest)) {
    const pkgViteConfig = resolve(process.cwd(), `packages/${remoteName}/vite.config.js`);
    let exposesKeys = [];

    if (existsSync(pkgViteConfig)) {
      try {
        const content = readFileSync(pkgViteConfig, "utf-8");
        // Simple regex extractor for exposed module keys
        const exposesMatch = content.match(/exposes:\s*\{([^}]+)\}/s);
        if (exposesMatch && exposesMatch[1]) {
          const keyMatches = [...exposesMatch[1].matchAll(/["'](\.[^"']+)["']\s*:/g)];
          exposesKeys = keyMatches.map((m) => m[1]);
        }
      } catch (err) {
        console.warn(`[generate-remotes-dts] Could not inspect vite.config.js for ${remoteName}:`, err.message);
      }
    }

    // Default fallback exposed modules if regex could not extract
    if (exposesKeys.length === 0) {
      if (remoteName === "demoService") {
        exposesKeys = ["./App", "./MfeDevWidget"];
      } else {
        exposesKeys = ["./App"];
      }
    }

    for (const exposeKey of exposesKeys) {
      const cleanSubpath = exposeKey.replace(/^\.\//, "");
      const moduleSpecifier = `${remoteName}/${cleanSubpath}`;

      if (cleanSubpath === "MfeDevWidget") {
        declarations.push(
          `declare module "${moduleSpecifier}" {`,
          `  import { ComponentType } from "react";`,
          `  export interface MfeDevWidgetProps {`,
          `    title?: string;`,
          `  }`,
          `  const MfeDevWidget: ComponentType<MfeDevWidgetProps>;`,
          `  export default MfeDevWidget;`,
          `}`,
          ""
        );
      } else if (cleanSubpath === "mount") {
        declarations.push(
          `declare module "${moduleSpecifier}" {`,
          `  export function mount(container: HTMLElement, props?: Record<string, any>): (() => void) | void;`,
          `  export const unmount: ((container: HTMLElement) => void) | undefined;`,
          `}`,
          ""
        );
      } else {
        declarations.push(
          `declare module "${moduleSpecifier}" {`,
          `  import { ComponentType } from "react";`,
          `  const Component: ComponentType<any>;`,
          `  export default Component;`,
          `}`,
          ""
        );
      }
    }
  }

  try {
    writeFileSync(TARGET_DTS_PATH, declarations.join("\n"), "utf-8");
    console.log(`[generate-remotes-dts] Successfully generated: ${TARGET_DTS_PATH}`);
  } catch (err) {
    console.error(`[generate-remotes-dts] Failed writing ${TARGET_DTS_PATH}:`, err.message);
  }
}

// Execute when invoked directly via Node
if (process.argv[1]?.endsWith("generate-remotes-dts.js")) {
  generateRemotesDts();
}

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const MANIFEST_PATH = resolve(process.cwd(), "remotes.manifest.json");
const TARGET_DTS_PATH = resolve(process.cwd(), "packages/host/src/remotes.d.ts");

export function generateRemotesDts() {
  if (!existsSync(MANIFEST_PATH)) {
    console.warn(`[generate-remotes-dts] Manifest not found at: ${MANIFEST_PATH}. Skipping generation.`);
    return;
  }

  let manifest;
  try {
    manifest = JSON.parse(readFileSync(MANIFEST_PATH, "utf-8"));
  } catch (err) {
    console.warn(`[generate-remotes-dts] Failed to parse manifest: ${err.message}. Skipping generation.`);
    return;
  }

  const declarations = [
    "/**",
    " * Ambient Module Declarations for Federated Micro-Frontend Remotes.",
    " * Auto-generated by scripts/generate-remotes-dts.js from remotes.manifest.json.",
    " * DO NOT EDIT DIRECTLY.",
    " */",
    "",
  ];

  for (const [remoteName, config] of Object.entries(manifest)) {
    const pkgViteConfig = resolve(process.cwd(), `packages/${remoteName}/vite.config.js`);
    let exposesKeys = [];

    if (existsSync(pkgViteConfig)) {
      try {
        const content = readFileSync(pkgViteConfig, "utf-8");
        // Robust regex matching key-value pairs inside exposes
        const keyMatches = [...content.matchAll(/["'](\.\/[a-zA-Z0-9_-]+)["']\s*:\s*["'][^"']+["']/g)];
        if (keyMatches.length > 0) {
          exposesKeys = keyMatches.map((m) => m[1]);
        }
      } catch (err) {
        console.warn(`[generate-remotes-dts] Could not inspect vite.config.js for ${remoteName}:`, err.message);
      }
    }

    // Default fallback exposed module
    if (exposesKeys.length === 0) {
      exposesKeys = ["./App"];
    }

    for (const exposeKey of exposesKeys) {
      const cleanSubpath = exposeKey.replace(/^\.\//, "");
      const moduleSpecifier = `${remoteName}/${cleanSubpath}`;

      if (cleanSubpath === "mount") {
        declarations.push(
          `declare module "${moduleSpecifier}" {`,
          `  export function mount(container: HTMLElement, props?: Record<string, any>): (() => void) | void;`,
          `  export const unmount: ((container: HTMLElement) => void) | undefined;`,
          `}`,
          ""
        );
      } else {
        declarations.push(
          `declare module "${moduleSpecifier}" {`,
          `  import { ComponentType } from "react";`,
          `  const Component: ComponentType<any>;`,
          `  export default Component;`,
          `}`,
          ""
        );
      }
    }
  }

  try {
    writeFileSync(TARGET_DTS_PATH, declarations.join("\n"), "utf-8");
    console.log(`[generate-remotes-dts] Successfully generated: ${TARGET_DTS_PATH}`);
  } catch (err) {
    console.error(`[generate-remotes-dts] Failed writing ${TARGET_DTS_PATH}:`, err.message);
  }

  generateRemotesRegistry();
}

const TARGET_REGISTRY_PATH = resolve(process.cwd(), "packages/host/src/remotesRegistry.jsx");

/**
 * Normalizes a single path string and calculates its route specificity score.
 * - Multi-segment subpaths have highest specificity (100 + segments*10 + length)
 * - Exact root path ("/") has score 10
 * - Catch-all wildcard ("/*" or "*") has score 0
 *
 * @param {string} rawPath
 * @param {string} remoteName
 * @returns {{ path: string, urlPath: string, isWildcard: boolean, isRoot: boolean, score: number }}
 */
export function normalizeRoutePath(rawPath, remoteName = "remote") {
  if (!rawPath || typeof rawPath !== "string") {
    return {
      path: `/${remoteName}/*`,
      urlPath: `/${remoteName}`,
      isWildcard: false,
      isRoot: false,
      score: 110,
    };
  }

  const trimmed = rawPath.trim();

  // Explicit global catch-all
  if (trimmed === "/*" || trimmed === "*") {
    return {
      path: "/*",
      urlPath: "/",
      isWildcard: true,
      isRoot: false,
      score: 0,
    };
  }

  // Exact root route - NEVER convert to /*
  if (trimmed === "/" || trimmed === "") {
    return {
      path: "/",
      urlPath: "/",
      isWildcard: false,
      isRoot: true,
      score: 10,
    };
  }

  // Subpath route: normalize to cleanPath without trailing slashes or wildcards
  const cleanPath = trimmed.replace(/\/\*$/, "").replace(/\/+$/, "") || "/";
  const normalizedPath = trimmed.endsWith("/*")
    ? trimmed
    : `${cleanPath}/*`;

  const segments = cleanPath.split("/").filter(Boolean);
  
  // Weighted specificity scoring:
  // - Static exact segments: +100 points
  // - Dynamic parameterized segments (:id): +40 points
  // - Wildcard segments (*): +5 points
  // - Segment depth multiplier: +10 per segment
  // - Minor tiebreaker: string length
  let segmentScore = 0;
  for (const seg of segments) {
    if (seg.startsWith(":")) {
      segmentScore += 40;
    } else if (seg === "*") {
      segmentScore += 5;
    } else {
      segmentScore += 100;
    }
  }

  const score = segmentScore + segments.length * 10 + cleanPath.length;

  return {
    path: normalizedPath,
    urlPath: cleanPath.startsWith("/") ? cleanPath : `/${cleanPath}`,
    isWildcard: false,
    isRoot: false,
    score,
  };
}

/**
 * Resolves and sorts all remote routes from manifest declarations.
 * Supports cfg.path (string or array), cfg.paths (array), and cfg.routes (array).
 * Routes are sorted by specificity: deep subpaths first, exact root ("/") next, and wildcards ("/*") last.
 *
 * @param {Record<string, any>} manifest
 * @returns {Array<{ key: string, name: string, path: string, urlPath: string, port: number|null, framework: string, isWildcard: boolean, isRoot: boolean, score: number }>}
 */
export function resolveRemoteRoutes(manifest = {}) {
  const routes = [];
  const wildcardRemotes = new Set();
  const seenPaths = new Map();

  for (const [name, cfg] of Object.entries(manifest || {})) {
    const rawPaths = Array.isArray(cfg.paths)
      ? cfg.paths
      : Array.isArray(cfg.routes)
      ? cfg.routes
      : Array.isArray(cfg.path)
      ? cfg.path
      : [cfg.path || `/${name}`];

    for (const raw of rawPaths) {
      const normalized = normalizeRoutePath(raw, name);

      if (normalized.isWildcard) {
        if (wildcardRemotes.size > 0) {
          console.warn(
            `[generate-remotes-dts] ⚠️  Sequential Wildcard Collision: '${name}' declares catch-all wildcard ('/*'), but '${Array.from(wildcardRemotes).join(", ")}' already declared a catch-all. Subsequent catch-all routes will be dead zones.`
          );
        }
        wildcardRemotes.add(name);
      }

      if (seenPaths.has(normalized.path)) {
        console.warn(
          `[generate-remotes-dts] ⚠️  Route Collision: Path '${normalized.path}' declared by '${name}' collides with previously registered remote '${seenPaths.get(normalized.path)}'.`
        );
      } else {
        seenPaths.set(normalized.path, name);
      }

      const cleanSub = normalized.urlPath.replace(/^\//, "").replace(/\//g, "-") || "root";
      const key = `${name}-${cleanSub}`;

      routes.push({
        key,
        name,
        path: normalized.path,
        urlPath: normalized.urlPath,
        port: cfg.port || null,
        framework: cfg.framework || "react",
        isWildcard: normalized.isWildcard,
        isRoot: normalized.isRoot,
        score: normalized.score,
      });
    }
  }

  // Sort routes strictly by specificity: highest score first
  routes.sort((a, b) => b.score - a.score);

  return routes;
}

export function generateRemotesRegistry() {
  if (!existsSync(MANIFEST_PATH)) return;

  let manifest;
  try {
    manifest = JSON.parse(readFileSync(MANIFEST_PATH, "utf-8"));
  } catch {
    return;
  }

  const resolvedRoutes = resolveRemoteRoutes(manifest);
  const hasNonReact = resolvedRoutes.some((r) => r.framework && r.framework !== "react");

  const code = [
    'import React from "react";',
    ...(hasNonReact ? ['import { UniversalRemoteMount } from "@subrataroy100/mfe-shared/adapters";'] : []),
    "",
    "/**",
    " * Manifest-Driven Remote Routes Registry.",
    " * Auto-generated by scripts/generate-remotes-dts.js from remotes.manifest.json.",
    " * Automatically ordered by route specificity (deep subpaths -> exact root -> catch-all).",
    " * DO NOT EDIT DIRECTLY.",
    " */",
    "export const remoteRoutes = [",
  ];

  for (const route of resolvedRoutes) {
    if (route.framework && route.framework !== "react") {
      code.push(`  {`);
      code.push(`    key: ${JSON.stringify(route.key)},`);
      code.push(`    name: ${JSON.stringify(route.name)},`);
      code.push(`    path: ${JSON.stringify(route.path)},`);
      code.push(`    urlPath: ${JSON.stringify(route.urlPath)},`);
      code.push(`    port: ${JSON.stringify(route.port)},`);
      code.push(`    Component: () => (`);
      code.push(`      <UniversalRemoteMount`);
      code.push(`        loadRemote={() => import(/* @vite-ignore */ ${JSON.stringify(`${route.name}/App`)})}`);
      code.push(`        remoteName=${JSON.stringify(route.name)}`);
      code.push(`      />`);
      code.push(`    ),`);
      code.push(`    framework: ${JSON.stringify(route.framework)},`);
      code.push(`  },`);
    } else {
      code.push(`  {`);
      code.push(`    key: ${JSON.stringify(route.key)},`);
      code.push(`    name: ${JSON.stringify(route.name)},`);
      code.push(`    path: ${JSON.stringify(route.path)},`);
      code.push(`    urlPath: ${JSON.stringify(route.urlPath)},`);
      code.push(`    port: ${JSON.stringify(route.port)},`);
      code.push(`    Component: React.lazy(() => import(${JSON.stringify(`${route.name}/App`)})),`);
      code.push(`    framework: "react",`);
      code.push(`  },`);
    }
  }

  code.push("];");
  code.push("");

  try {
    writeFileSync(TARGET_REGISTRY_PATH, code.join("\n"), "utf-8");
    console.log(`[generate-remotes-dts] Successfully generated: ${TARGET_REGISTRY_PATH}`);
  } catch (err) {
    console.error(`[generate-remotes-dts] Failed writing ${TARGET_REGISTRY_PATH}:`, err.message);
  }
}

// Execute when invoked directly via Node
if (process.argv[1]?.endsWith("generate-remotes-dts.js")) {
  generateRemotesDts();
}
